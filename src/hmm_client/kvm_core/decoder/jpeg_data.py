TAIL: bytes = bytes([0xFF, 0xD9])   # EOI marker


# ----- Mutable state (matches Java's static dqttags field) -----
_dqt_tags: int = 4   # default 50% quality


def set_dqt_tags(value: int) -> None:
    """Java's `JPEGData.setdqttags(int)` — selects DQT quality."""
    global _dqt_tags
    _dqt_tags = max(0, min(9, value))


def get_dqt_tags() -> int:
    """Java's `JPEGData.getdqttags()`."""
    return _dqt_tags


def create_syn_head_data() -> bytes:
    """Java's `JPEGData.createSynHeadData()`.

    Build the synthetic JPEG header block: SOI + APP0 + DQT_Y +
    DQT_U + DQT_V + SOF (4:4:4) + DHT/SOS markers. Caller appends
    the chassis-sent JPEG body and the EOI tail (`TAIL`).
    """
    tables = DQT_TABLES_BY_QUALITY[_dqt_tags]
    if tables is None:
        # Fall back to quality 50% when the requested level isn't
        # ported yet. Java would throw NullPointerException;
        # we degrade gracefully.
        tables = DQT_TABLES_BY_QUALITY[4]
        assert tables is not None
    dqt_y, dqt_u, dqt_v = tables
    return (HEAD_SYN_SOI_APPO
            + dqt_y + dqt_u + dqt_v
            + HEAD_SYN_SOF_444
            + HEAD_SYN_SOF_SOS)

"""Port of `com.kvm.decoder.JPEGData` + `DQTZData`.

The chassis NewRLE codec sometimes uses **JPEG tiles** (zip_type 2 or 3
in the tile token) for high-detail 64×64 regions. The chassis sends
ONLY the JPEG entropy-coded body — the SOI, APP0, DQT, DHT, SOF
markers are STRIPPED to save bandwidth.

Java's `ImageDecoder.decodeRLEorJPEG1` reconstructs the missing
markers via `JPEGData.createSynHeadData()`, prepends them to the
received body, appends the EOI marker, and feeds the result to
`ImageIO.read()`. We do the same here: build the synthetic header
bytes and let PIL decode the assembled JPEG.

The DQT (Discrete Quantization Table) values come in 10 quality
variants (10%, 20%, ..., 100%). The chassis selects which one applies
via the `dqt_tags` value carried in the chunk-zero header (`bytes[18]
& 0x0F`); Java sets it via `JPEGData.setdqttags`. We expose the same
state, defaulting to quality 50% (index 4) which is what the
JPEGData default tables in the Java source ship with.
"""
